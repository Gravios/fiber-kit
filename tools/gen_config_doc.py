#!/usr/bin/env python3
"""Generate docs/config.md from the shipped configs, and check the knob inventory.

docs/config.md was written by hand and drifted: it documented knob names no code reads any more, missed
most of the knobs the shipped fiber-kit-exp.yaml sets, and quoted defaults the yaml no longer has.  The
yaml's own comments are the maintained description of every knob, so the page is generated from them:

  * one section per `#  [X] TITLE` banner of src/fiber_kit/fiber-kit-exp.yaml, in file order;
  * one row per FK_* key: its value in fiber-kit-exp.yaml, its value in fiber-kit.yaml (— when that
    file leaves it to the built-in default) and the comment, continuation lines joined.

    python3 tools/gen_config_doc.py           # rewrite docs/config.md
    python3 tools/gen_config_doc.py --check   # exit 1 when docs/config.md is stale, or when the code
                                              # reads an FK_* knob that fiber-kit-exp.yaml does not list

run_all.py runs --check.  RUNNER lists the FK_* variables that are not tuning knobs (the runner's own
plumbing); LEGACY lists names still honoured for old configs but superseded.
"""
import argparse
import glob
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, ".."))
EXP = os.path.join(ROOT, "src", "fiber_kit", "fiber-kit-exp.yaml")
BASE = os.path.join(ROOT, "src", "fiber_kit", "fiber-kit.yaml")
DOC = os.path.join(ROOT, "docs", "config.md")

RUNNER = {"FK_CONFIG", "FK_DIR", "FK_DRYRUN", "FK_ELEC", "FK_KEY", "FK_PYTHON", "FK_SESS", "FK_SPK_VARIANT"}
LEGACY = {"FK_REFINE_DEDUP_STRICT": "FK_REFINE_DEDUP_STALE"}

BANNER = re.compile(r"^#\s+\[([A-Z0-9])\]\s+(.*\S)\s*$")
ENTRY = re.compile(r"""^(FK_[A-Z0-9_]+):\s*("(?:[^"\\]|\\.)*"|'[^']*'|[^\s#]+)\s*(?:#\s?(.*))?$""")
CONT = re.compile(r"^\s{8,}#\s?(.*)$")
SUB = re.compile(r"^#\s*-{3,}\s+(.*?)\s*-{3,}\s*$")

INTRO = """# fiber-kit — configuration knobs (`FK_*`)

<!-- GENERATED by tools/gen_config_doc.py from src/fiber_kit/fiber-kit-exp.yaml and fiber-kit.yaml.
     Edit the yaml comments, then run the tool; run_all.py checks this page is current. -->

Stages read tuning knobs with precedence **CLI flag / plan `params:` > `FK_*` environment variable >
`$FK_CONFIG` yaml > built-in default** (config.knob_value).  Set them in your `fiber-kit.yaml` (pointed to
by `$FK_CONFIG`; `fiber-kit-exp.yaml` is the shipped experimental profile, `fiber-kit.yaml` the
production one), in the environment, or per step in a plan.

Values are read with YAML 1.2 booleans: `off`, `on`, `yes` and `no` are the words written, and only
`true`/`false` are booleans.  A value that is not one of a knob's choices, or not a number where one is
needed, stops the stage with the knob's name.

Each table lists a knob's value in **fiber-kit-exp.yaml** and in **fiber-kit.yaml** (— = not set there:
the built-in default applies), then the yaml's own description, which usually starts with
`default | range`.
"""


def parse(path):
    """[(section_id, title, [(key, value, text)])] in file order, plus {key: value}."""
    sections, values = [], {}
    cur = ("", "General", [])
    sections.append(cur)
    last = None
    with open(path) as fh:
        lines = fh.read().splitlines()
    for ln in lines:
        m = BANNER.match(ln)
        if m:
            cur = (m.group(1), m.group(2), [])
            sections.append(cur)
            last = None
            continue
        m = SUB.match(ln)
        if m and m.group(1):
            cur[2].append(("###", m.group(1), ""))
            last = None
            continue
        m = ENTRY.match(ln)
        if m:
            key, val, txt = m.group(1), m.group(2), (m.group(3) or "").strip()
            if val[:1] in "\"'" and val[-1:] == val[:1]:
                val = val[1:-1]
            values[key] = val
            last = [key, val, txt]
            cur[2].append(last)
            continue
        m = CONT.match(ln)
        if m and last is not None:
            last[2] = (last[2] + " " + m.group(1).strip()).strip()
            continue
        if not ln.strip().startswith("#") or ln.startswith("#"):
            last = None
    return [s for s in sections if any(r[0] != "###" for r in s[2])], values


def code_knobs():
    names = set()
    paths = glob.glob(os.path.join(ROOT, "src", "fiber_kit", "*.py")) + [os.path.join(ROOT, "scripts",
                                                                                      "fiber-pipeline")]
    for p in paths:
        with open(p, errors="replace") as fh:
            names |= set(re.findall(r"\bFK_[A-Z0-9_]*[A-Z0-9]\b", fh.read()))
    return names


def esc(s):
    return s.replace("|", "\\|")


def render():
    sections, exp = parse(EXP)
    _, base = parse(BASE)
    out = [INTRO]
    for sid, title, rows in sections:
        out.append(f"\n## {'[' + sid + '] ' if sid else ''}{title}\n")
        head = True
        for key, val, txt in rows:
            if key == "###":
                out.append(f"\n### {val}\n")
                head = True
                continue
            if head:
                out.append("| knob | fiber-kit-exp.yaml | fiber-kit.yaml | meaning |")
                out.append("|---|---|---|---|")
                head = False
            b = base.get(key)
            bv = "—" if b is None else f"`{esc(b) if b != '' else chr(34) * 2}`"
            out.append(f"| `{key}` | `{esc(val) if val != '' else chr(34) * 2}` | {bv} | {esc(txt)} |")
    only_base = sorted(set(base) - set(exp))
    if only_base:
        out.append("\n## Set only in fiber-kit.yaml\n")
        out.append("| knob | fiber-kit.yaml |")
        out.append("|---|---|")
        out += [f"| `{k}` | `{esc(base[k])}` |" for k in only_base]
    if LEGACY:
        out.append("\n## Legacy names\n")
        out.append("Still honoured for old configs; use the replacement.\n")
        out.append("| legacy | use |")
        out.append("|---|---|")
        out += [f"| `{k}` | `{v}` |" for k, v in sorted(LEGACY.items())]
    return "\n".join(out) + "\n", exp, base


def main(argv=None):
    ap = argparse.ArgumentParser(prog="gen_config_doc")
    ap.add_argument("--check", action="store_true", help="exit 1 when docs/config.md or the yaml is stale")
    a = ap.parse_args(argv)
    text, exp, base = render()
    missing = sorted(k for k in code_knobs() - set(exp) - set(base) - RUNNER - set(LEGACY)
                     if not k.endswith("_"))
    if a.check:
        bad = 0
        with open(DOC) as fh:
            if fh.read() != text:
                print("DRIFT: docs/config.md does not match the yaml -- run tools/gen_config_doc.py"); bad = 1
        if missing:
            print("MISSING: knobs the code reads that neither shipped yaml lists: " + ", ".join(missing))
            bad = 1
        if not bad:
            print(f"OK: docs/config.md matches the yaml ({len(exp)} knobs); every knob the code reads is listed")
        return bad
    with open(DOC, "w") as fh:
        fh.write(text)
    print(f"wrote docs/config.md ({len(exp)} knobs from fiber-kit-exp.yaml)")
    if missing:
        print("note: knobs the code reads that neither yaml lists: " + ", ".join(missing))
    return 0


if __name__ == "__main__":
    sys.exit(main())
