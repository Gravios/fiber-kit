#!/usr/bin/env python3
"""The shipped fiber-kit config PROFILES, and `fiber-kit-init` -- write one as ./fiber-kit.yaml.

``fiber-kit.yaml`` is the flat ``FK_*`` tuning config (with its embedded ``pipeline:`` plan) that
``fiber-pipeline`` and every stage read from the working directory they run in.  Three profiles ship in
the package:

    base   fiber-kit.yaml        the production config (fiber-link as the linker)
    exp    fiber-kit-exp.yaml    the experimental config: the newest gates on, fiber-anchor-link
    best   fiber-kit-best.yaml   exp with the fiber-tune exp-search winner applied (g6 0316, 2026-11-07),
                                 knobs ordered by relevance; generated by tools/gen_best_profile.py

`fk set config --profile best` (or `fiber-kit-init --profile best`) copies one into the current directory
as fiber-kit.yaml, to edit there; `fk list config` lists them and says which one ./fiber-kit.yaml is.
A profile is named by its short name, its file name, or a path to any yaml of your own.
"""
import argparse
import hashlib
import os
import re
import sys

try:
    from importlib.resources import files
except ImportError:                                   # py<3.9 fallback (requires-python is >=3.9)
    from importlib_resources import files             # type: ignore

TEMPLATE = "fiber-kit.yaml"
EXP_TEMPLATE = "fiber-kit-exp.yaml"
BEST_TEMPLATE = "fiber-kit-best.yaml"
PROFILES = {"base": TEMPLATE, "exp": EXP_TEMPLATE, "best": BEST_TEMPLATE}   # short name -> packaged file
TARGET = "fiber-kit.yaml"                                                      # what a session folder reads


def profile_text(name):
    """(resolved profile name, file name, text) for a short name, a packaged file name (with or without
    .yaml / the fiber-kit- prefix) or a path.  ValueError when nothing matches."""
    n = str(name).strip()
    short = n[:-5] if n.endswith(".yaml") else n
    short = short[len("fiber-kit-"):] if short.startswith("fiber-kit-") else short
    if short == "fiber-kit":
        short = "base"
    if short in PROFILES and os.sep not in n and not os.path.isfile(n):
        fn = PROFILES[short]
        try:
            return short, fn, (files("fiber_kit") / fn).read_text(encoding="utf-8")
        except (FileNotFoundError, ModuleNotFoundError, OSError) as e:
            raise ValueError(f"packaged profile {fn} not found: {e}") from None
    if os.path.isfile(n):
        with open(n, encoding="utf-8") as fh:
            return os.path.basename(n), n, fh.read()
    raise ValueError(f"no profile {name!r}: one of {', '.join(PROFILES)} (or a path to a yaml)")


def describe(text):
    """One line about a profile: the first header line after the file name (its '--' tagline)."""
    for ln in text.splitlines()[:6]:
        m = re.match(r"^#\s+fiber-kit[\w-]*\.yaml\s+(?:-+|\u2014)\s+(.*\S)\s*$", ln)
        if m:
            return m.group(1)
    return ""


def summarize(text):
    """(number of FK_* knobs, plan step names) of a profile's text, without PyYAML."""
    knobs = len(re.findall(r"^FK_[A-Z0-9_]+:", text, re.M))
    steps = re.findall(r"^\s*-\s*\{stage:\s*[\w-]+,\s*name:\s*([\w.-]+)", text, re.M)
    return knobs, steps


def _digest(text):
    return hashlib.sha1(text.encode("utf-8")).hexdigest()


def current_profile(target=TARGET):
    """Which profile ./fiber-kit.yaml is: (short name, 'exact' | 'edited') or (None, None) when there is no
    file or it matches no shipped profile's header line."""
    if not os.path.isfile(target):
        return None, None
    with open(target, encoding="utf-8") as fh:
        text = fh.read()
    head = text.splitlines()[1:2]
    for short, fn in PROFILES.items():
        try:
            ptext = (files("fiber_kit") / fn).read_text(encoding="utf-8")
        except (FileNotFoundError, ModuleNotFoundError, OSError):
            continue
        if _digest(ptext) == _digest(text):
            return short, "exact"
        if head and head == ptext.splitlines()[1:2]:
            return short, "edited"
    return None, None


def list_profiles(names_only=False, target=TARGET, out=sys.stdout):
    """`fk list config`: the shipped profiles, and which one the target file is."""
    if names_only:
        for short in PROFILES:
            out.write(short + "\n")
        return 0
    cur, how = current_profile(target)
    rows = []
    for short, fn in PROFILES.items():
        try:
            text = (files("fiber_kit") / fn).read_text(encoding="utf-8")
        except (FileNotFoundError, ModuleNotFoundError, OSError):
            rows.append((short, fn, "(not packaged)", "", ""))
            continue
        knobs, steps = summarize(text)
        mark = ("*" if how == "exact" else "~") if short == cur else " "
        rows.append((mark + short, fn, describe(text), f"{knobs} knobs", f"{len(steps)} steps: " + " ".join(steps)))
    w0 = max(len(r[0]) for r in rows); w1 = max(len(r[1]) for r in rows)
    for r in rows:
        out.write(f"{r[0].ljust(w0)}  {r[1].ljust(w1)}  {r[2]}\n")
        out.write(f"{' ' * w0}  {' ' * w1}  {r[3]}, {r[4]}\n")
    if cur is None:
        out.write(f"\n./{target}: " + ("not present -- `fk set config --profile <name>` writes one\n"
                                      if not os.path.isfile(target) else "present, matches no shipped profile\n"))
    else:
        out.write(f"\n./{target}: {'the ' + cur + ' profile' if how == 'exact' else 'an edited copy of the ' + cur + ' profile'}"
                  "  (* exact, ~ edited)\n")
    return 0


def set_profile(profile, output=TARGET, force=False, err=sys.stderr, out=sys.stdout):
    """`fk set config --profile P`: write the profile as `output` (default ./fiber-kit.yaml)."""
    try:
        short, fn, text = profile_text(profile)
    except ValueError as e:
        err.write(f"fk set config: {e}\n")
        return 2
    dst = output
    if os.path.exists(dst) and not force:
        cur, how = current_profile(dst)
        what = f"the {cur} profile" if how == "exact" else f"an edited copy of the {cur} profile" if cur else "a config"
        err.write(f"fk set config: {dst} already exists ({what}); use --force to overwrite it\n")
        return 1
    with open(dst, "w", encoding="utf-8") as fh:
        fh.write(text)
    knobs, steps = summarize(text)
    out.write(f"fk set config: wrote {dst} from {fn} ({short}: {knobs} knobs, {len(steps)} plan steps). "
              f"Edit it, then run fiber-pipeline <elec> or fk run <elec> from this directory.\n")
    return 0


def main(argv=None):
    ap = argparse.ArgumentParser(
        prog="fiber-kit-init",
        description="Write a shipped fiber-kit config profile (fiber-pipeline tuning config + plan) into the "
                    "current directory as fiber-kit.yaml.  The same as `fk set config`; `fk list config` lists "
                    "the profiles.")
    ap.add_argument("-p", "--profile", default=None,
                    help="profile: " + ", ".join(f"{k} ({v})" for k, v in PROFILES.items())
                         + ", or a path to a yaml (default: base; --exp = exp)")
    ap.add_argument("-o", "--output", default=TARGET, help="destination path (default: ./fiber-kit.yaml)")
    ap.add_argument("-f", "--force", action="store_true", help="overwrite the destination if it already exists")
    ap.add_argument("--exp", action="store_true", help="the same as --profile exp (kept from earlier versions)")
    ap.add_argument("--list", action="store_true", help="list the profiles (as `fk list config`) and exit")
    a = ap.parse_args(argv)
    if a.list:
        return list_profiles()
    profile = a.profile or ("exp" if a.exp else "base")
    return set_profile(profile, a.output, a.force)


if __name__ == "__main__":
    sys.exit(main())
